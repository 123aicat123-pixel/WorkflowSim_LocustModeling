#!/usr/bin/env python3
"""Independent, frozen Montage-32 physical replay selection audit.

Input: precisely four same-run source artifacts generated by the new matrix.
Oracle truth is used *only* for retrospective scoring, never candidate choice.
This is a prospective independent FIXED-32 audit cohort, not unseen-family proof.
"""
import csv
import itertools
import math
import pathlib
import sys
from fla_independent32_k4_identifiability_audit import hv, dominates, planned_greedy

DAGS = ("Montage_50", "Montage_100")
PROFILES = ("default", "staggered")
POLICIES = (
    "all_vm0", "all_vm12", "round_robin", "stride7", "evenodd_vm0_vm12",
    "block4_vm0_vm12", "four_vm_round", "four_vm_block5",
    "vm0_vm12_skew75", "vm12_vm15_skew75", "prime_step5", "prime_step11",
    "hash_seed17", "hash_seed97", "monotonic_vm16",
    "reverse_monotonic_vm16", "cyclic_step3", "cyclic_step9",
    "two_vm_alt_3_11", "two_vm_block3_3_11", "four_vm_shift_round",
    "four_vm_shift_block", "eight_vm_odd_round", "eight_vm_odd_block",
    "vm0_vm12_skew90", "vm12_vm15_skew90", "reverse_round_robin",
    "reverse_stride7", "hash_seed211", "hash_seed307", "monotonic_vm8",
    "reverse_monotonic_vm8",
)
TOL = 1e-10
SOURCE_COLUMNS = (
    "workflow", "vm_profile", "seed", "mapping_policy", "task_count",
    "old_planned_makespan", "old_planned_cost",
    "ready_planned_makespan", "ready_planned_cost",
    "actual_makespan", "actual_cost",
    "old_start_mae", "ready_start_mae",
    "old_finish_mae", "ready_finish_mae", "task_vm_mapping",
)

def read(path):
    with path.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        assert reader.fieldnames == list(SOURCE_COLUMNS), (path,reader.fieldnames)
        return list(reader)

def write(path,rows):
    assert rows
    with path.open("w",newline="",encoding="utf-8") as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

def audit(root, out, expected_sha):
    out.mkdir(parents=True, exist_ok=True)
    artifacts=sorted(root.glob("fla-montage32-*/same_mapping_true_replays.csv"))
    assert len(artifacts)==4, ("Require four distinct new original source artifacts",artifacts)
    by_case={}
    for csvpath in artifacts:
        folder=csvpath.parent
        sha=(folder/"source-sha.txt").read_text().strip()
        assert sha==expected_sha, ("Mixed source revision", folder,sha,expected_sha)
        protocol=(folder/"protocol-sha.txt").read_text().strip()
        assert len(protocol)==40 and all(c in "0123456789abcdef" for c in protocol)
        rows=read(csvpath)
        assert len(rows)==32
        case=(rows[0]["workflow"], rows[0]["vm_profile"])
        assert case in set(itertools.product(DAGS,PROFILES)) and case not in by_case
        assert folder.name==f"fla-montage32-{case[0]}-{case[1]}"
        assert {r["mapping_policy"] for r in rows}==set(POLICIES)
        assert len({r["task_vm_mapping"] for r in rows})==32
        assert all((r["workflow"],r["vm_profile"])==case and r["seed"]=="1501" for r in rows)
        count=50 if case[0]=="Montage_50" else 100
        for r in rows:
            assert int(r["task_count"])==count
            mapping={}
            for item in r["task_vm_mapping"].split("|"):
                t,v=map(int,item.split(":"))
                assert t not in mapping
                mapping[t]=v
            assert set(mapping)==set(range(1,count+1))
            assert all(0<=v<16 for v in mapping.values())
            for key in SOURCE_COLUMNS[5:15]:
                value=float(r[key])
                assert math.isfinite(value) and (value>0 if "mae" not in key else value>=0)
        source_log=(folder/"source.log").read_text(errors="replace")
        assert source_log.count("FROZEN_MAP_UNIVERSE_PASS")==32
        assert "PASS thirty-two disjoint algorithm-independent source genotypes" in source_log
        by_case[case]=rows
    assert set(by_case)==set(itertools.product(DAGS, PROFILES))
    results=[]
    for case in itertools.product(DAGS,PROFILES):
        rows=by_case[case]
        names=[r["mapping_policy"] for r in rows]
        actual={r["mapping_policy"]:(float(r["actual_makespan"]),
                                      float(r["actual_cost"])) for r in rows}
        reference=tuple(1.5*max(p[i] for p in actual.values())+1e-6 for i in (0,1))
        all_true_hv=hv(list(actual.values()), reference)
        nd=sum(not any(dominates(other,pt) for other in actual.values() if other!=pt)
               for pt in actual.values())
        oracles={}
        ties={}
        for k in range(1,5):
            best=-1.0
            num=0
            for combination in itertools.combinations(actual.values(),k):
                value=hv(combination,reference)
                if value>best+TOL:
                    best=value
                    num=1
                elif abs(value-best)<=TOL:
                    num+=1
            oracles[k],ties[k]=best,num
        selected={}
        for model in ("old","ready"):
            planned=[(float(r[f"{model}_planned_makespan"]),
                      float(r[f"{model}_planned_cost"])) for r in rows]
            selected[model]=planned_greedy(planned,names,4)
            assert len(selected[model])==4 and len(set(selected[model]))==4
        record=dict(workflow=case[0],vm_profile=case[1],
                    source_sha=expected_sha,truth_rows=len(rows),
                    true_nd_count=nd,full_true_hv=all_true_hv,
                    exact_k4_oracle=oracles[4],exact_k4_ties=ties[4],
                    full_minus_k4=all_true_hv-oracles[4],
                    k4_minus_k3=oracles[4]-oracles[3],
                    blind_first_four_hv=hv([actual[x] for x in names[:4]],reference),
                    old_order="|".join(selected["old"]),
                    ready_order="|".join(selected["ready"]))
        for k in range(1,5):
            chosen={}
            for model in ("old","ready"):
                chosen[model]=selected[model][:k]
                value=hv([actual[x] for x in chosen[model]],reference)
                regret=max(0.,oracles[k]-value)
                assert regret>=0 and value<=oracles[k]+TOL
                record[f"{model}_k{k}_actual_hv"]=value
                record[f"{model}_k{k}_regret"]=regret
            record[f"k{k}_oracle"]=oracles[k]
            record[f"k{k}_set_differs"]=int(set(chosen["old"])!=set(chosen["ready"]))
            record[f"k{k}_ready_minus_old_actual_hv"]=(
                record[f"ready_k{k}_actual_hv"]-record[f"old_k{k}_actual_hv"])
        results.append(record)
    write(out/"montage32_exact_k1_k4_decision_audit.csv",results)
    lines=[
        "# Frozen Montage-32 original WorkflowSim actual decision audit",
        "",
        "Prospective fixed-mapping transfer cohort only. Montage was used elsewhere in",
        "the project; this is **not** an untouched family or an optimizer study.",
        f"Source SHA: \`{expected_sha}\`; four unique blocks; 128 original true replays.",
        "All 32 maps per block preserved; exact C(32,4)=35,960 hindsight oracle;",
        "forecast-only OLD/READY physical choices, no label-guided selection.",
        "",
        "| DAG | VM profile | True ND | K4 ties | K4 regret OLD | K4 regret READY | K4 set different |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for r in results:
        lines.append(
            f"| {r['workflow']} | {r['vm_profile']} | {r['true_nd_count']} | "
            f"{r['exact_k4_ties']} | {r['old_k4_regret']:.9f} | "
            f"{r['ready_k4_regret']:.9f} | {r['k4_set_differs']} |")
    lines+=["",
      "| K | OLD vs READY different selected sets | OLD mean regret | READY mean regret | Mean READY minus OLD actual HV |",
      "|---:|---:|---:|---:|---:|"]
    for k in range(1,5):
        lines.append(f"| {k} | {sum(r[f'k{k}_set_differs'] for r in results)}/4 | "
            f"{sum(r[f'old_k{k}_regret'] for r in results)/4:.9f} | "
            f"{sum(r[f'ready_k{k}_regret'] for r in results)/4:.9f} | "
            f"{sum(r[f'k{k}_ready_minus_old_actual_hv'] for r in results)/4:+.9f} |")
    lines+=["",
      "If all physical selections coincide, **no model decision advantage is demonstrated**.",
      "If any differ, report positive AND negative regret differences without tuning.",
      "These four blocks reuse one simulator seed, and Montage is not a fully untouched",
      "family; neither a positive nor a null result establishes SCI-level significance."]
    (out/"montage32_findings.md").write_text("\n".join(lines)+"\n", encoding="utf-8")
    print("\n".join(lines))

if __name__=="__main__":
    assert len(sys.argv)==4, "Usage: audit.py SOURCE_DIR OUTPUT_DIR EXACT_SOURCE_SHA"
    audit(pathlib.Path(sys.argv[1]),pathlib.Path(sys.argv[2]),sys.argv[3])
